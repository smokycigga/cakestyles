"""Download the site's webfonts and emit a self-hosted @font-face stylesheet.

The storefront used to pull Playfair Display and Poppins from
fonts.googleapis.com. On a phone that costs two extra origins (googleapis for
the CSS, gstatic for the files), each with its own DNS lookup and TLS
handshake, and the CSS is render-blocking — measured at ~1.6s before first
paint on a throttled 4G profile.

Run:  python scripts/fetch-fonts.py
Writes: client/public/fonts/*.woff2 and client/public/fonts/fonts.css
"""

import pathlib
import re
import urllib.request

# Playfair Display is a variable font: asking for a weight *range* returns one
# file per style that covers every weight, instead of one file per weight. That
# is 2 files (~60KB) rather than 4 (~135KB) for the same typography.
# Poppins has no variable version on Google Fonts, so its weights stay separate
# — but they are small (~8KB each) and the browser only fetches the ones used.
CSS_URL = (
    "https://fonts.googleapis.com/css2?"
    "family=Playfair+Display:ital,wght@0,400..900;1,400..900"
    "&family=Poppins:wght@300;400;500;600;700&display=swap"
)

# Only the latin subset is kept — the storefront is English. Google also serves
# cyrillic, vietnamese, latin-ext and devanagari blocks, none of which any page
# here renders.
KEEP_SUBSET = "latin"

OUT_DIR = pathlib.Path("client/public/fonts")
CSS_OUT = OUT_DIR / "fonts.css"

HEADER = """/* Self-hosted webfonts — generated by scripts/fetch-fonts.py.
 *
 * These used to come from fonts.googleapis.com, which cost two extra origins
 * and a render-blocking stylesheet (~1.6s on a throttled phone). Serving the
 * same files from our own origin removes both round trips.
 *
 * Latin subset only. Regenerate with: python scripts/fetch-fonts.py
 */
"""


def fetch(url: str) -> bytes:
    # The User-Agent matters: Google serves woff2 with subset comments only to
    # browsers that advertise woff2 support. A generic agent gets a different,
    # un-splittable stylesheet.
    req = urllib.request.Request(
        url,
        headers={
            "User-Agent": (
                "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 "
                "(KHTML, like Gecko) Chrome/120.0.0.0 Safari/537.36"
            )
        },
    )
    with urllib.request.urlopen(req, timeout=60) as response:
        return response.read()


def main() -> None:
    print("fetching stylesheet…")
    css = fetch(CSS_URL).decode("utf-8")

    # Google writes "/* subset */" immediately before each @font-face block.
    blocks = re.findall(r"/\*\s*([a-z-]+)\s*\*/\s*(@font-face\s*\{[^}]*\})", css)
    print(f"  {len(blocks)} @font-face blocks")

    OUT_DIR.mkdir(parents=True, exist_ok=True)
    rules: list[str] = [HEADER]
    total = 0
    written = 0

    for subset, block in blocks:
        if subset != KEEP_SUBSET:
            continue

        family = re.search(r"font-family:\s*'([^']+)'", block)
        style = re.search(r"font-style:\s*(\w+)", block)
        weight = re.search(r"font-weight:\s*([\d ]+);", block)
        url = re.search(r"url\((https://[^)]+)\)", block)
        if not (family and style and weight and url):
            print(f"  skipping an unparsable {subset} block")
            continue

        slug = family.group(1).lower().replace(" ", "-")
        weight_label = weight.group(1).strip().replace(" ", "-")
        name = f"{slug}-{style.group(1)}-{weight_label}.woff2"
        dest = OUT_DIR / name

        if not dest.exists():
            dest.write_bytes(fetch(url.group(1)))
        written += 1
        size = dest.stat().st_size
        total += size
        print(f"  {name:38} {size / 1024:6.1f} KB")

        rules.append("@font-face {")
        rules.append(f"  font-family: '{family.group(1)}';")
        rules.append(f"  font-style: {style.group(1)};")
        rules.append(f"  font-weight: {weight.group(1)};")
        # swap: text paints in the fallback immediately rather than waiting.
        rules.append("  font-display: swap;")
        rules.append(f"  src: url('/fonts/{name}') format('woff2');")
        unicode_range = re.search(r"unicode-range:[^;]+;", block)
        if unicode_range:
            rules.append(f"  {unicode_range.group(0)}")
        rules.append("}")
        rules.append("")

    CSS_OUT.write_text("\n".join(rules), encoding="utf-8")
    print(f"\n{written} files, {total / 1024:.0f} KB total")
    print(f"wrote {CSS_OUT}")


if __name__ == "__main__":
    main()
